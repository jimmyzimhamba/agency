-- ============================================================================
-- Agency Command — Grid Plan Review, Part 2: Data Model
-- ============================================================================
-- Adds the tables behind the "Client Grid Plan Review" feature: the agency
-- builds a grid of upcoming posts, shares a private link with a client, and
-- the client reviews/comments/approves in-browser with no login.
--
-- PREREQUISITE: migration_grid_roles.sql must already be applied (this file
-- uses grid_can_manage()/grid_can_edit() from it).
-- HOW TO RUN: Supabase Dashboard → SQL Editor → paste this whole file → Run.
-- Safe to re-run.
--
-- SECURITY MODEL — read this before touching anything below:
--   These four tables get RLS enabled with policies ONLY for `authenticated`
--   org members (via my_org_id(), same pattern as every other table in this
--   app). There is deliberately NO anon/public policy on any of them. The
--   public, no-login client review page (/review/:share_token) must NEVER
--   talk to Supabase directly with the anon key — it goes entirely through
--   dedicated Edge Functions (review-load / review-update / review-reorder /
--   review-complete, added separately) which use the service-role key
--   server-side and validate the share_token themselves. That's what keeps
--   a client from ever being able to query another agency's data, no matter
--   what the browser sends.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. grid_plans — one per client review ("Acme Coffee — October grid")
-- ----------------------------------------------------------------------------
create table if not exists public.grid_plans (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete cascade,
  client_name text not null,
  -- Per-client accent color for the review page — profiles.color already
  -- established this "#rrggbb text column" convention elsewhere.
  accent_color text not null default '#7b2ff7',
  status text not null default 'draft'
    check (status in ('draft', 'shared', 'in_review', 'changes_requested', 'approved')),
  -- Long, random, unguessable — generated by the app when the plan is first
  -- shared (not by the DB), so a plan sitting in 'draft' has no token yet.
  -- Unique so a token can only ever resolve to exactly one plan (this is
  -- what the review-load Edge Function relies on for cross-plan isolation).
  share_token text unique,
  share_token_expires_at timestamptz,
  shared_at timestamptz,
  -- Set by the review-complete Edge Function when the client finishes;
  -- separate from `status = 'approved'` so "changes requested" still counts
  -- as the client having completed a review pass.
  client_completed_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_grid_plans_org on public.grid_plans (org_id);
create index if not exists idx_grid_plans_share_token on public.grid_plans (share_token);

alter table public.grid_plans enable row level security;

drop policy if exists "grid_plans: read org" on public.grid_plans;
create policy "grid_plans: read org" on public.grid_plans
  for select using (org_id = public.my_org_id());

drop policy if exists "grid_plans: managers create" on public.grid_plans;
create policy "grid_plans: managers create" on public.grid_plans
  for insert with check (org_id = public.my_org_id() and public.grid_can_manage());

drop policy if exists "grid_plans: managers update" on public.grid_plans;
create policy "grid_plans: managers update" on public.grid_plans
  for update using (org_id = public.my_org_id() and public.grid_can_manage())
  with check (org_id = public.my_org_id() and public.grid_can_manage());

drop policy if exists "grid_plans: managers delete" on public.grid_plans;
create policy "grid_plans: managers delete" on public.grid_plans
  for delete using (org_id = public.my_org_id() and public.grid_can_manage());

drop trigger if exists trg_grid_plans_org on public.grid_plans;
create trigger trg_grid_plans_org
  before insert on public.grid_plans
  for each row execute function public.stamp_org_id();

drop trigger if exists trg_grid_plans_touch on public.grid_plans;
create trigger trg_grid_plans_touch
  before update on public.grid_plans
  for each row execute function public.touch_updated_at();

-- ----------------------------------------------------------------------------
-- 2. grid_posts — one per tile in the grid
-- ----------------------------------------------------------------------------
create table if not exists public.grid_posts (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.grid_plans (id) on delete cascade,
  org_id uuid not null references public.organizations (id) on delete cascade,
  position integer not null default 0,
  caption text not null default '',
  -- Deliberately a SEPARATE column from `caption`. A client once pasted an
  -- entire rewritten caption into what was meant to be a short note field,
  -- and it had to be migrated by hand — the review-page UI must keep these
  -- two fields visually distinct (see the review-page build step), and the
  -- data model keeps them structurally distinct here too.
  client_note text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'changes_requested')),
  post_date date,
  platform text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_grid_posts_plan on public.grid_posts (plan_id, position);
create index if not exists idx_grid_posts_org on public.grid_posts (org_id);

alter table public.grid_posts enable row level security;

drop policy if exists "grid_posts: read org" on public.grid_posts;
create policy "grid_posts: read org" on public.grid_posts
  for select using (org_id = public.my_org_id());

drop policy if exists "grid_posts: editors write" on public.grid_posts;
