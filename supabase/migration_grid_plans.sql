-- ----------------------------------------------------------------------------
-- 4. grid_activity — audit trail, mirrors the existing activity_log pattern.
--    Populated two ways:
--      a) automatically, by the trigger below, whenever a grid_posts row's
--         content actually changes (agency edits AND client edits routed
--         through the service-role Edge Functions both fire it — triggers
--         run regardless of RLS/service-role bypass);
--      b) manually, by app/Edge Function code, for events that aren't a
--         plain row UPDATE (e.g. "plan shared", "client approved", and
--         keep-both conflict resolutions, which log the discarded version
--         into before_value).
-- ----------------------------------------------------------------------------
create table if not exists public.grid_activity (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete cascade,
  plan_id uuid not null references public.grid_plans (id) on delete cascade,
  post_id uuid references public.grid_posts (id) on delete set null,
  -- 'agency' = a signed-in team member did this; 'client' = it came through
  -- a review-* Edge Function call authenticated only by share_token.
  actor_type text not null check (actor_type in ('agency', 'client')),
  actor_id uuid references public.profiles (id) on delete set null,
  action text not null,
  before_value jsonb,
  after_value jsonb,
  message text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_grid_activity_plan on public.grid_activity (plan_id, created_at desc);
create index if not exists idx_grid_activity_org on public.grid_activity (org_id);

alter table public.grid_activity enable row level security;

drop policy if exists "grid_activity: read org" on public.grid_activity;
create policy "grid_activity: read org" on public.grid_activity
  for select using (org_id = public.my_org_id());

-- Agency-side manual inserts (e.g. logging "plan shared") — anyone who can
-- edit the plan's content can also write an activity row. The Edge
-- Functions use the service-role key, which bypasses RLS entirely, so
-- client-originated inserts don't need (and don't get) a policy here.
drop policy if exists "grid_activity: editors insert" on public.grid_activity;
create policy "grid_activity: editors insert" on public.grid_activity
  for insert with check (org_id = public.my_org_id() and public.grid_can_edit());

-- Auto-log real content changes on grid_posts. Security definer so it can
-- write to grid_activity regardless of who/what triggered the update
-- (signed-in teammate OR the service-role Edge Function on the client's
-- behalf, which has no auth.uid()).
create or replace function public.log_grid_post_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  changed_fields jsonb := '{}'::jsonb;
  before_fields jsonb := '{}'::jsonb;
  who uuid := auth.uid();
begin
  if new.caption is distinct from old.caption then
    before_fields := before_fields || jsonb_build_object('caption', old.caption);
    changed_fields := changed_fields || jsonb_build_object('caption', new.caption);
  end if;
  if new.client_note is distinct from old.client_note then
    before_fields := before_fields || jsonb_build_object('client_note', old.client_note);
    changed_fields := changed_fields || jsonb_build_object('client_note', new.client_note);
  end if;
  if new.status is distinct from old.status then
    before_fields := before_fields || jsonb_build_object('status', old.status);
    changed_fields := changed_fields || jsonb_build_object('status', new.status);
  end if;
  if new.position is distinct from old.position then
    before_fields := before_fields || jsonb_build_object('position', old.position);
    changed_fields := changed_fields || jsonb_build_object('position', new.position);
  end if;

  if changed_fields = '{}'::jsonb then
    return new;
  end if;

  insert into public.grid_activity (org_id, plan_id, post_id, actor_type, actor_id, action, before_value, after_value, message)
  values (
    new.org_id,
    new.plan_id,
    new.id,
    case when who is null then 'client' else 'agency' end,
    who,
    'post_updated',
    before_fields,
    changed_fields,
    'Post updated'
  );

  return new;
end;
$$;

drop trigger if exists trg_log_grid_post_changes on public.grid_posts;
create trigger trg_log_grid_post_changes
  after update on public.grid_posts
  for each row execute function public.log_grid_post_changes();

-- ----------------------------------------------------------------------------
-- 5. Storage: private `grid-media` bucket
-- ----------------------------------------------------------------------------
-- public = false, unlike the existing `avatars` bucket — media is only ever
-- served via signed URLs (agency side: normal authenticated storage RLS
-- below; client side: a short-lived signed URL minted by the review-load
-- Edge Function using the service-role key). No policy here ever allows an
-- anonymous/public read.
insert into storage.buckets (id, name, public)
values ('grid-media', 'grid-media', false)
on conflict (id) do nothing;

-- Path convention: "<org_id>/<plan_id>/<filename>" — mirrors the avatars
-- bucket's "<user_id>/filename" folder-prefix pattern. Only signed-in
-- members of that org can read/write inside their own org's folder.
drop policy if exists "grid-media: org read" on storage.objects;
create policy "grid-media: org read" on storage.objects
  for select using (
    bucket_id = 'grid-media'
    and (storage.foldername(name))[1] = public.my_org_id()::text
  );

drop policy if exists "grid-media: editors upload" on storage.objects;
create policy "grid-media: editors upload" on storage.objects
  for insert with check (
    bucket_id = 'grid-media'
    and (storage.foldername(name))[1] = public.my_org_id()::text
    and public.grid_can_edit()
  );

drop policy if exists "grid-media: editors delete" on storage.objects;
create policy "grid-media: editors delete" on storage.objects
  for delete using (
    bucket_id = 'grid-media'
    and (storage.foldername(name))[1] = public.my_org_id()::text
    and public.grid_can_edit()
  );

-- ----------------------------------------------------------------------------
-- 6. Realtime: add the two live-editing tables to the same publication
--    every other realtime table in this app already uses.
-- ----------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'grid_posts'
  ) then
    alter publication supabase_realtime add table public.grid_posts;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'grid_plans'
  ) then
    alter publication supabase_realtime add table public.grid_plans;
  end if;
end $$;

